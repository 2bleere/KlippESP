#!/usr/bin/env python3
"""Generate the boot logo assets from assets/logo_source.png (needs Pillow).

    python3 tools/gen_logo.py [source.png]

Writes src/boot_logo.c (RGB565 LVGL image + background color) and src/web_logo.h (PNG for the web page).
The visible artwork (anything brighter than the background) is detected and cropped to a centered square with a
small margin, so any logo on a plain dark background works in landscape and portrait.
"""
import io
import zlib
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "logo_source.png")
# boot logo size per board (build flag -> px); the last entry is the default for any other board
BOOT_SIZES = [("BOARD_WAVESHARE_S3_LCD7", 340), (None, 260)]  # 800x480 panel / 480x320 panel
WEB_SIZE = 160    # px PNG for the settings page


def main():
    im = Image.open(SRC).convert("RGB")
    w, h = im.size
    px = im.load()
    bg = px[8, 8]  # background color from the corner
    # bounding box of everything that stands out from the background (glow included)
    xs, ys = [], []
    for y in range(0, h, 2):
        for x in range(0, w, 2):
            r, g, b = px[x, y]
            if abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2]) > 60:
                xs.append(x)
                ys.append(y)
    if not xs:
        sys.exit("no artwork found")
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    side = int(max(x1 - x0, y1 - y0) * 1.12)  # ~6 % margin per side, so rounded corners on the web page clip nothing
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    box = (cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2)
    canvas = Image.new("RGB", (w + side, h + side), bg)
    canvas.paste(im, (side // 2, side // 2))
    crop = canvas.crop(tuple(v + side // 2 for v in box))

    lines = ["// Generated by tools/gen_logo.py from assets/logo_source.png. Do not edit.",
             "// One size per board; only the selected board's image is compiled.",
             "#include <lvgl.h>", "",
             "const uint32_t BOOT_LOGO_BG = 0x%02X%02X%02X;" % bg, ""]
    total = 0
    for n, (flag, size) in enumerate(BOOT_SIZES):
        lines.append(("#if defined(%s)" % flag if n == 0 else "#elif defined(%s)" % flag) if flag else "#else")
        boot = crop.resize((size, size), Image.LANCZOS)
        data = bytearray()
        raw = boot.tobytes()
        for i in range(0, len(raw), 3):
            r, g, b = raw[i], raw[i + 1], raw[i + 2]
            v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            data += bytes((v & 0xFF, v >> 8))  # little endian RGB565 (LV_COLOR_16_SWAP 0)
        lines.append("#define BOOT_LOGO_SIZE %d" % size)
        lines.append("static const uint8_t boot_logo_map[] = {")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",")
        lines.append("};")
        total += len(data)
    lines += ["#endif", "",
              "const lv_img_dsc_t boot_logo = {",
              "    {LV_IMG_CF_TRUE_COLOR, 0, 0, BOOT_LOGO_SIZE, BOOT_LOGO_SIZE},",
              "    sizeof(boot_logo_map),",
              "    boot_logo_map,",
              "};", ""]
    open(os.path.join(ROOT, "src", "boot_logo.c"), "w").write("\n".join(lines))

    web = crop.resize((WEB_SIZE, WEB_SIZE), Image.LANCZOS).quantize(colors=96, method=Image.MEDIANCUT)
    buf = io.BytesIO()
    web.save(buf, "PNG", optimize=True)
    png = buf.getvalue()
    hl = ["#pragma once", "// Generated by tools/gen_logo.py. Do not edit.", "#include <stdint.h>", "#include <stddef.h>", "",
          "static const uint8_t WEB_LOGO_PNG[] = {"]
    for i in range(0, len(png), 24):
        hl.append("    " + ",".join("0x%02X" % b for b in png[i:i + 24]) + ",")
    hl += ["};", "static const size_t WEB_LOGO_PNG_LEN = sizeof(WEB_LOGO_PNG);",
           "// changes with the image; appended to /logo.png so browsers fetch a new logo instead of a cached one",
           '#define WEB_LOGO_VER "%08x"' % zlib.crc32(png), ""]
    open(os.path.join(ROOT, "src", "web_logo.h"), "w").write("\n".join(hl))
    crop.resize((BOOT_SIZES[0][1],) * 2, Image.LANCZOS).save(os.path.join(ROOT, "assets", "boot_logo_preview.png"))
    print("frame %s, crop %s, bg #%02X%02X%02X, boot %d bytes (all sizes), web png %d bytes" % ((x0, y0, x1, y1), box, *bg, total, len(png)))


if __name__ == "__main__":
    main()
