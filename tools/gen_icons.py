#!/usr/bin/env python3
"""Regenerate the Material Design Icons subset fonts used by the dashboard.

Needs Node.js. Run from anywhere:

    python3 tools/gen_icons.py

Installs lv_font_conv and @mdi/font into a temporary directory, renders the icons
listed below at 16/20/28/72 px into src/fonts/, and writes src/ui_icons.h with
ICON_* UTF-8 string macros. To add an icon, look up its name at
https://pictogrammers.com/library/mdi/ and add it to ICONS.
"""
import os
import re
import subprocess
import sys
import tempfile

ICONS = [
    ("NOZZLE", "printer-3d-nozzle"), ("BED", "heat-wave"), ("THERMO", "thermometer"), ("FAN", "fan"),
    ("FAN_OFF", "fan-off"), ("SPEED", "speedometer"), ("FLOW", "water"), ("LAYERS", "layers-triple-outline"),
    ("CLOCK", "clock-outline"), ("HOURGLASS", "timer-sand"), ("Z", "axis-z-arrow"), ("PRINTER", "printer-3d"),
    ("CHIP", "chip"), ("PI", "raspberry-pi"), ("WIFI_1", "wifi-strength-1"), ("WIFI_2", "wifi-strength-2"),
    ("WIFI_3", "wifi-strength-3"), ("WIFI_4", "wifi-strength-4"), ("WIFI_OFF", "wifi-off"),
    ("LAN_OFF", "lan-disconnect"), ("OK", "check-circle"), ("ALERT", "alert-circle"), ("STOP", "alert-octagon"),
    ("PAUSE", "pause-circle"), ("PLAY", "play-circle"), ("CLOSE", "close-circle"), ("HOTSPOT", "access-point"),
    ("CUBE", "cube-outline"), ("POS", "crosshairs-gps"), ("FILAMENT", "movie-roll"), ("HOME", "home-outline"),
    ("STARTUP", "progress-wrench"), ("NOZZLE_ALERT", "printer-3d-nozzle-alert"), ("CHAMBER", "home-thermometer-outline"),
    ("FIRE", "fire"), ("SYNC", "sync"), ("TIMER", "timer-outline"),
    ("CPU", "cpu-64-bit"), ("MEMORY", "memory"), ("DISK", "harddisk"), ("POWER_ALERT", "flash-alert"),
    ("UPTIME", "timer-play-outline"), ("SERVER", "server"),
]
SIZES = {16: "lv_font_montserrat_16", 20: "lv_font_montserrat_20", 28: "lv_font_montserrat_28", 72: "lv_font_montserrat_48"}
MDI_VERSION = "7.4.47"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def main():
    work = tempfile.mkdtemp(prefix="klippesp-icons-")
    run = lambda *a: subprocess.run(a, cwd=work, check=True)
    run("npm", "init", "-y")
    run("npm", "install", "--silent", "lv_font_conv@1.5.2", "@mdi/font@" + MDI_VERSION)
    mdi = os.path.join(work, "node_modules", "@mdi", "font")
    names = dict(re.findall(r'^\s+"([a-z0-9-]+)": ([0-9A-F]+),?$', open(os.path.join(mdi, "scss", "_variables.scss")).read(), re.M))
    codes = []
    for macro, name in ICONS:
        if name not in names:
            sys.exit("unknown icon: " + name)
        codes.append((macro, int(names[name], 16)))
    rng = ",".join(hex(c) for _, c in codes)
    os.makedirs(os.path.join(SRC, "fonts"), exist_ok=True)
    for size in SIZES:
        font = "icons_%d" % size
        out = os.path.join(SRC, "fonts", font + ".c")
        run("npx", "lv_font_conv", "--font", os.path.join(mdi, "fonts", "materialdesignicons-webfont.ttf"),
            "-r", rng, "--size", str(size), "--bpp", "4", "--format", "lvgl", "--lv-include", "lvgl.h",
            "--no-compress", "-o", out)
        s = open(out).read()
        # writable struct so ui_icons_init() can attach a Montserrat fallback for plain text
        s, n = re.subn(r"const lv_font_t %s = \{" % font, "lv_font_t %s = {" % font, s)
        assert n, font
        open(out, "w").write(s)

    h = ["#pragma once",
         "// Material Design Icons subset (@mdi/font %s, Apache-2.0). Generated by tools/gen_icons.py." % MDI_VERSION,
         "// Fonts icons_16 / icons_20 / icons_28 / icons_72; plain text falls back to Montserrat (see ui_icons_init).",
         "#include <lvgl.h>", "", "extern lv_font_t icons_16, icons_20, icons_28, icons_72;", "void ui_icons_init();", ""]
    for macro, c in codes:
        h.append('#define ICON_%-13s "%s"' % (macro, "".join("\\x%02X" % b for b in chr(c).encode())))
    open(os.path.join(SRC, "ui_icons.h"), "w").write("\n".join(h) + "\n")
    print("generated %d icons in %d sizes" % (len(codes), len(SIZES)))


if __name__ == "__main__":
    main()
